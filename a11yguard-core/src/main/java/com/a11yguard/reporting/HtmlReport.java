package com.a11yguard.reporting;

import com.a11yguard.core.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;

public final class HtmlReport implements AccessibilityReport {
    @Override public ReportFormat format() { return ReportFormat.HTML; }

    @Override
    public Path write(List<AccessibilityResult> results, Path dir) throws Exception {
        Files.createDirectories(dir);
        Path out = dir.resolve("a11yguard-report.html");
        StringBuilder h = new StringBuilder();
        h.append("""
<!doctype html><html><head><meta charset="utf-8">
<title>A11yGuard Accessibility Report</title>
<style>
body{font-family:Arial,sans-serif;margin:0;background:#f6f7f9;color:#222}
header{padding:28px;background:#1f2937;color:#fff} main{padding:24px;max-width:1400px;margin:auto}
.cards{display:grid;grid-template-columns:repeat(4,1fr);gap:14px}.card{background:#fff;padding:18px;border-radius:10px;box-shadow:0 1px 4px #ddd}
.card b{font-size:28px;display:block;margin-top:6px} table{width:100%;border-collapse:collapse;background:#fff;margin:12px 0 28px}
th,td{padding:10px;border-bottom:1px solid #eee;text-align:left;vertical-align:top}th{background:#f0f2f5}
.badge{padding:3px 7px;border-radius:10px;font-weight:bold}.critical,.serious{background:#fee2e2}.moderate{background:#fef3c7}.minor{background:#e0f2fe}
details{background:#fff;margin:8px 0;padding:12px;border-radius:8px}code,pre{white-space:pre-wrap;word-break:break-word}
.small{color:#666;font-size:12px}
</style></head><body><header><h1>A11yGuard Accessibility Report</h1></header><main>
""");
        long tests=results.size(), violations=ReportUtil.violationCount(results), incomplete=ReportUtil.incompleteCount(results);
        h.append("<div class='cards'>");
        h.append(card("Tests", String.valueOf(tests))).append(card("Violations", String.valueOf(violations)))
         .append(card("Incomplete / manual review", String.valueOf(incomplete)))
         .append(card("Pages scanned", String.valueOf(results.stream().map(AccessibilityResult::url).distinct().count())));
        h.append("</div><h2>Test executions</h2><table><tr><th>Framework</th><th>Test</th><th>URL</th><th>Standard</th><th>Violations</th><th>Incomplete</th><th>Timestamp</th></tr>");
        for (AccessibilityResult r: results) {
            h.append("<tr><td>").append(ReportUtil.esc(r.framework())).append("</td><td>").append(ReportUtil.esc(r.testName()))
             .append("</td><td>").append(ReportUtil.esc(r.url())).append("</td><td>").append(ReportUtil.esc(r.standard()))
             .append("</td><td>").append(r.violations().size()).append("</td><td>").append(r.incomplete().size())
             .append("</td><td>").append(ReportUtil.esc(String.valueOf(r.timestamp()))).append("</td></tr>");
        }
        h.append("</table><h2>Violation details</h2>");
        for (AccessibilityResult r: results) {
            h.append("<details><summary><b>").append(ReportUtil.esc(r.testName())).append("</b> — ")
             .append(ReportUtil.esc(r.url())).append(" (").append(r.violations().size()).append(")</summary>");
            if (r.pageScreenshot() != null && !r.pageScreenshot().isBlank()) {
                h.append("<p><img src='").append(ReportUtil.esc(r.pageScreenshot()))
                 .append("' alt='page screenshot' style='max-width:100%'></p>");
            }
            h.append("<table><tr><th>Impact</th><th>Rule</th><th>Description</th><th>Help</th><th>Target</th><th>HTML</th><th>Screenshot</th></tr>");
            for (AccessibilityViolation v: r.violations()) row(h,v);
            h.append("</table>");
            if (!r.suppressed().isEmpty()) {
                h.append("<h3>Suppressed / baseline</h3><p class='small'>")
                 .append(r.suppressed().size()).append(" known issues ignored.</p>");
            }
            if (!r.incomplete().isEmpty()) {
                h.append("<h3>Incomplete / manual review</h3><table><tr><th>Impact</th><th>Rule</th><th>Description</th><th>Help</th><th>Target</th></tr>");
                for (AccessibilityViolation v: r.incomplete()) {
                    h.append("<tr><td>").append(badge(v)).append("</td><td>").append(ReportUtil.esc(v.id()))
                     .append("</td><td>").append(ReportUtil.esc(v.description())).append("</td><td>")
                     .append(link(v.helpUrl(),v.help())).append("</td><td>").append(ReportUtil.esc(ReportUtil.target(v))).append("</td></tr>");
                }
                h.append("</table>");
            }
            h.append("</details>");
        }
        h.append("<p class='small'>Generated by A11yGuard. Automated accessibility results should be complemented by manual testing where applicable.</p></main></body></html>");
        Files.writeString(out,h.toString(), StandardCharsets.UTF_8);
        return out;
    }
    private static StringBuilder card(String name,String val){ return new StringBuilder("<div class='card'>").append(ReportUtil.esc(name)).append("<b>").append(val).append("</b></div>"); }
    private static String badge(AccessibilityViolation v){String c=ReportUtil.safe(v.impact()).toLowerCase(); return "<span class='badge "+c+"'>"+ReportUtil.esc(v.impact())+"</span>";}
    private static String link(String url,String text){return url==null||url.isBlank()?ReportUtil.esc(text):"<a href='"+ReportUtil.esc(url)+"' target='_blank' rel='noreferrer'>"+ReportUtil.esc(text)+"</a>";}
    private static void row(StringBuilder h,AccessibilityViolation v){
        h.append("<tr><td>").append(badge(v)).append("</td><td>").append(ReportUtil.esc(v.id()))
         .append("</td><td>").append(ReportUtil.esc(v.description())).append("</td><td>")
         .append(link(v.helpUrl(),v.help())).append("</td><td><code>").append(ReportUtil.esc(ReportUtil.target(v)))
         .append("</code></td><td><code>").append(ReportUtil.esc(v.html())).append("</code></td><td>");
        if (v.screenshot() != null && !v.screenshot().isBlank()) {
            h.append("<img src='").append(ReportUtil.esc(v.screenshot()))
             .append("' alt='").append(ReportUtil.esc(v.id())).append("' style='max-width:240px'>");
        }
        h.append("</td></tr>");
    }
}
