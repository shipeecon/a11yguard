import * as fs from "fs";
import * as path from "path";
import {
  AccessibilityResult,
  AccessibilityViolation,
  ReportFormat
} from "./types";

const results: AccessibilityResult[] = [];

function esc(s: string | undefined): string {
  return (s || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function csv(s: string | undefined): string {
  return `"${(s || "").replace(/"/g, '""')}"`;
}

function target(v: AccessibilityViolation): string {
  return (v.target || []).join(" | ");
}

function writeHtml(all: AccessibilityResult[], dir: string): void {
  const violations = all.reduce((n, r) => n + r.violations.length, 0);
  const incomplete = all.reduce((n, r) => n + r.incomplete.length, 0);
  const pages = new Set(all.map((r) => r.url)).size;
  const rows = all
    .map(
      (r) =>
        `<tr><td>${esc(r.framework)}</td><td>${esc(r.testName)}</td><td>${esc(r.url)}</td><td>${esc(r.standard)}</td><td>${r.violations.length}</td><td>${r.incomplete.length}</td><td>${esc(r.timestamp)}</td></tr>`
    )
    .join("");
  const details = all
    .map((r) => {
      const shot = r.pageScreenshot
        ? `<p><img src="${esc(r.pageScreenshot)}" alt="page screenshot" style="max-width:100%"></p>`
        : "";
      const vrows = r.violations
        .map((v) => {
          const img = v.screenshot
            ? `<img src="${esc(v.screenshot)}" alt="${esc(v.id)}" style="max-width:240px">`
            : "";
          return `<tr><td><span class="badge ${(v.impact || "").toLowerCase()}">${esc(v.impact)}</span></td><td>${esc(v.id)}</td><td>${esc(v.description)}</td><td>${esc(v.help)}</td><td><code>${esc(target(v))}</code></td><td><code>${esc(v.html)}</code></td><td>${img}</td></tr>`;
        })
        .join("");
      return `<details><summary><b>${esc(r.testName)}</b> — ${esc(r.url)} (${r.violations.length})</summary>${shot}<table><tr><th>Impact</th><th>Rule</th><th>Description</th><th>Help</th><th>Target</th><th>HTML</th><th>Screenshot</th></tr>${vrows}</table></details>`;
    })
    .join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>A11yGuard Accessibility Report</title>
<style>
body{font-family:Arial,sans-serif;margin:0;background:#f6f7f9;color:#222}
header{padding:28px;background:#1f2937;color:#fff} main{padding:24px;max-width:1400px;margin:auto}
.cards{display:grid;grid-template-columns:repeat(4,1fr);gap:14px}.card{background:#fff;padding:18px;border-radius:10px}
.card b{font-size:28px;display:block;margin-top:6px} table{width:100%;border-collapse:collapse;background:#fff;margin:12px 0 28px}
th,td{padding:10px;border-bottom:1px solid #eee;text-align:left;vertical-align:top}th{background:#f0f2f5}
.badge{padding:3px 7px;border-radius:10px;font-weight:bold}.critical,.serious{background:#fee2e2}.moderate{background:#fef3c7}.minor{background:#e0f2fe}
details{background:#fff;margin:8px 0;padding:12px;border-radius:8px}code{white-space:pre-wrap;word-break:break-word}
.small{color:#666;font-size:12px}
</style></head><body><header><h1>A11yGuard Accessibility Report</h1></header><main>
<div class="cards"><div class="card">Tests<b>${all.length}</b></div><div class="card">Violations<b>${violations}</b></div><div class="card">Incomplete / manual review<b>${incomplete}</b></div><div class="card">Pages scanned<b>${pages}</b></div></div>
<h2>Test executions</h2><table><tr><th>Framework</th><th>Test</th><th>URL</th><th>Standard</th><th>Violations</th><th>Incomplete</th><th>Timestamp</th></tr>${rows}</table>
<h2>Violation details</h2>${details}
<p class="small">Generated by A11yGuard. Automated accessibility results should be complemented by manual testing where applicable.</p>
</main></body></html>`;
  fs.writeFileSync(path.join(dir, "a11yguard-report.html"), html);
}

function writeJson(all: AccessibilityResult[], dir: string): void {
  fs.writeFileSync(
    path.join(dir, "a11yguard-report.json"),
    JSON.stringify(all, null, 2)
  );
}

function writeMarkdown(all: AccessibilityResult[], dir: string): void {
  const violations = all.reduce((n, r) => n + r.violations.length, 0);
  const incomplete = all.reduce((n, r) => n + r.incomplete.length, 0);
  let md = `# A11yGuard Accessibility Report\n\n| Metric | Count |\n|---|---:|\n| Tests | ${all.length} |\n| Violations | ${violations} |\n| Incomplete / manual review | ${incomplete} |\n\n## Test executions\n\n| Framework | Test | URL | Standard | Violations | Incomplete |\n|---|---|---|---|---:|---:|\n`;
  for (const r of all) {
    md += `| ${r.framework} | ${r.testName} | ${r.url} | ${r.standard} | ${r.violations.length} | ${r.incomplete.length} |\n`;
  }
  md += "\n## Violation details\n\n";
  for (const r of all) {
    for (const v of r.violations) {
      md += `### ${v.id} — ${v.impact}\n- **Test:** ${r.testName}\n- **Description:** ${v.description}\n- **Help:** ${v.help}\n- **Help URL:** ${v.helpUrl}\n- **Target:** \`${target(v)}\`\n\n`;
    }
  }
  fs.writeFileSync(path.join(dir, "a11yguard-report.md"), md);
}

function writeCsv(all: AccessibilityResult[], dir: string): void {
  let s =
    "framework,testName,url,standard,timestamp,status,type,impact,ruleId,description,help,helpUrl,target,html\n";
  for (const r of all) {
    if (r.violations.length === 0 && r.incomplete.length === 0) {
      s += `${csv(r.framework)},${csv(r.testName)},${csv(r.url)},${csv(r.standard)},${csv(r.timestamp)},PASS,,,,,,,,\n`;
    }
    for (const v of r.violations) {
      s += `${csv(r.framework)},${csv(r.testName)},${csv(r.url)},${csv(r.standard)},${csv(r.timestamp)},FAIL,VIOLATION,${csv(v.impact)},${csv(v.id)},${csv(v.description)},${csv(v.help)},${csv(v.helpUrl)},${csv(target(v))},${csv(v.html)}\n`;
    }
  }
  fs.writeFileSync(path.join(dir, "a11yguard-report.csv"), s);
}

function writeJunit(all: AccessibilityResult[], dir: string): void {
  const failures = all.filter((r) => r.violations.length).length;
  let x = `<?xml version="1.0" encoding="UTF-8"?>\n<testsuite name="A11yGuard" tests="${all.length}" failures="${failures}" skipped="0">\n`;
  for (const r of all) {
    x += `  <testcase classname="${esc(r.framework)}" name="${esc(r.testName)}">\n`;
    if (r.violations.length) {
      x += `    <failure message="Accessibility violations found"><![CDATA[`;
      for (const v of r.violations) x += `[${v.impact}] ${v.id} - ${v.help} - ${target(v)}\n`;
      x += `]]></failure>\n`;
    }
    x += `  </testcase>\n`;
  }
  x += `</testsuite>\n`;
  fs.writeFileSync(path.join(dir, "a11yguard-report.xml"), x);
}

function writeSarif(all: AccessibilityResult[], dir: string): void {
  const sarifResults = all.flatMap((r) =>
    r.violations.map((v) => ({
      ruleId: v.id,
      level: ["critical", "serious"].includes((v.impact || "").toLowerCase())
        ? "error"
        : "warning",
      message: { text: v.help || v.description },
      locations: [
        { physicalLocation: { artifactLocation: { uri: r.url || "" } } }
      ],
      helpUri: v.helpUrl,
      properties: {
        description: v.description,
        target: target(v),
        html: v.html,
        framework: r.framework,
        testName: r.testName
      }
    }))
  );
  const root = {
    $schema: "https://json.schemastore.org/sarif-2.1.0.json",
    version: "2.1.0",
    runs: [{ tool: { driver: { name: "A11yGuard" } }, results: sarifResults }]
  };
  fs.writeFileSync(path.join(dir, "a11yguard-report.sarif"), JSON.stringify(root, null, 2));
}

export function report(
  result: AccessibilityResult,
  reportDir: string,
  formats: ReportFormat[]
): void {
  results.push(result);
  fs.mkdirSync(reportDir, { recursive: true });
  const writers: Record<ReportFormat, (all: AccessibilityResult[], dir: string) => void> = {
    HTML: writeHtml,
    JSON: writeJson,
    MARKDOWN: writeMarkdown,
    CSV: writeCsv,
    JUNIT_XML: writeJunit,
    SARIF: writeSarif
  };
  for (const format of formats) writers[format](results, reportDir);
}

export function writeExitCode(reportDir: string, failOn: string[]): void {
  const fail = results.some((r) =>
    r.violations.some((v) => failOn.includes(severityOfImpact(v.impact)))
  );
  fs.mkdirSync(reportDir, { recursive: true });
  fs.writeFileSync(path.join(reportDir, "a11yguard-exit-code"), fail ? "1\n" : "0\n");
}

export function assertAccessible(
  result: AccessibilityResult,
  failOn: string[]
): void {
  const failing = result.violations.filter((v) =>
    failOn.includes(severityOfImpact(v.impact))
  );
  if (!failing.length) return;
  const details = failing
    .map((v) => `[${v.impact}] ${v.id} - ${v.help} - ${target(v)}`)
    .join("\n");
  throw new Error(`Accessibility violations found at ${result.url}\n${details}`);
}

function severityOfImpact(impact: string | undefined): string {
  switch ((impact || "").toLowerCase()) {
    case "critical":
      return "CRITICAL";
    case "serious":
      return "SERIOUS";
    case "moderate":
      return "MODERATE";
    default:
      return "MINOR";
  }
}
